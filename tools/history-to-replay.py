"""Turn a Beyond Nations history (JSON Lines from tools/BeyondNations.HistoryExport) into a
shareable replay in usd-recorder's usd-replay/1 contract.

    uv run --python 3.12 tools/history-to-replay.py history.jsonl out/seed12.usdc --stride 800

The replay (usd-recorder docs/REPLAY.md) is one Z-up layer that any usd-replay/1 player can show,
for example usd-web's browser player (``usd-web replay out/seed12.usdc -o site/replay``):

``Entities``  pawns and settlements in their nation's colour (a pawn with no nation is grey),
              chickens, trees and saplings; pawns inside a settlement are left out, as the game
              does not draw them either. Sizes are exaggerated (``SIZES``) so they read at map scale.
``Fields``    ``ground``: one cell per 15-unit ground tile over every chunk generated by the end,
              in Core's tile colour tinted by territory (the nearest settlement within
              ``settlementJoinRange``, the rule a pawn uses to pick a nation to join; the same
              rule tools/history-to-usd.py draws). Tiles not generated yet are dark.
``Stats``     day, pawns, settlements, nations, chickens.

Core keeps no state hash, so ``replay:stateHash`` is a hash of the exported state at each sample:
SHA-256 (first 16 hex digits) of the canonical JSON of every entity's id, kind, nation and
position plus the nation table, as rebuilt from the export stream. It proves the export is
reproducible (HistoryExport's own tests check that a seed gives byte-identical output), not
Core's full internal state. The coordinates map Core's Y-up (x, y, z) to the replay's Z-up
(x, -z, y). This is a tool outside the game: it reads the export and nothing else.
"""

from __future__ import annotations

import argparse
import hashlib
import json
import sys
from collections.abc import Iterator
from pathlib import Path

import numpy as np
from usd_recorder.replay import ReplayWriter

FORMAT = "beyond-nations-history/1"
TERRITORY_TINT = 0.6  # as tools/history-to-usd.py
GROUND_SOFTEN = 0.15  # Core tiles are (0, random, 0); keep a little of the noise
GROUND = (0.36, 0.38, 0.3)  # a muted olive, so territory colours stand out
UNGENERATED = (27 / 255, 32 / 255, 38 / 255)  # usd-web's replay background, so unexplored ground disappears
NO_NATION = (0.62, 0.64, 0.68)
# Drawn diameter per kind in world units (a ground tile is 15). Core's pawns are one unit wide,
# so true size would be invisible from far enough away to see the map.
SIZES = {"pawn": 28.0, "settlement": 70.0, "chicken": 10.0, "tree": 14.0, "sapling": 7.0}
SETS = (
    ("trees", ("tree",), "Trees", "#2f7d32", "sphere"),
    ("saplings", ("sapling",), "Saplings", "#7cbf5a", "sphere"),
    ("chickens", ("chicken",), "Chickens", "#f2efe6", "sphere"),
    ("settlements", ("settlement",), "Settlements", None, "cube"),
    ("pawns", ("pawn",), "Pawns", None, "sphere"),
)


def read_history(path: Path) -> Iterator[dict]:
    with path.open(encoding="utf-8") as handle:
        for number, line in enumerate(handle, 1):
            line = line.strip()
            if line:
                try:
                    yield json.loads(line)
                except json.JSONDecodeError as error:
                    raise SystemExit(f"{path}:{number}: not JSON: {error}") from error


def mix(a, b, t):
    return tuple(x + (y - x) * t for x, y in zip(a, b, strict=True))


def to_bytes(rgb) -> list[int]:
    return [max(0, min(255, round(c * 255))) for c in rgb]


def scan_chunks(path: Path) -> tuple[float, list[dict]]:
    """Every chunk record (first pass), and the tile size."""
    chunks, size = [], None
    for record in read_history(path):
        if record["t"] == "chunk":
            chunks.append(record)
            size = size or record["tiles"][0][2]
    if not chunks:
        raise SystemExit(f"{path}: no ground chunks")
    return float(size), chunks


class Ground:
    """The ground as one colour grid over every tile the run generates."""

    def __init__(self, chunks: list[dict], tile: float, join_range: float):
        xs = [t[0] for c in chunks for t in c["tiles"]]
        zs = [t[1] for c in chunks for t in c["tiles"]]
        self.tile = tile
        self.x0, self.z1 = min(xs), max(zs)
        self.cols = round((max(xs) - self.x0) / tile) + 1
        self.rows = round((self.z1 - min(zs)) / tile) + 1
        self.reach = join_range * join_range
        self.base = np.tile(np.array(UNGENERATED), (self.rows * self.cols, 1))
        self.generated = np.zeros(self.rows * self.cols, dtype=bool)
        # Tile centres in Core's x/z, per cell (row j runs along the replay's +y = Core's -z).
        i = np.arange(self.cols)
        j = np.arange(self.rows)
        self.cx = np.tile(self.x0 + i * tile, self.rows)
        self.cz = np.repeat(self.z1 - j * tile, self.cols)

    @property
    def origin(self) -> tuple[float, float]:
        # Replay (x, y) = Core (x, -z); cell (0, 0) is the tile at (x0, z1).
        return self.x0 - self.tile / 2, -self.z1 - self.tile / 2

    def add(self, record: dict) -> None:
        for x, z, _size, r, g, b in record["tiles"]:
            k = round((self.z1 - z) / self.tile) * self.cols + round((x - self.x0) / self.tile)
            self.base[k] = mix(GROUND, (r, g, b), GROUND_SOFTEN)
            self.generated[k] = True

    def colors(self, settlements: list[tuple[float, float, tuple]]) -> np.ndarray:
        out = self.base.copy()
        if settlements:
            best = np.full(len(out), self.reach)
            owner = np.full(len(out), -1)
            for n, (sx, sz, _) in enumerate(settlements):
                d = (self.cx - sx) ** 2 + (self.cz - sz) ** 2
                closer = d <= best
                best = np.where(closer, d, best)
                owner = np.where(closer, n, owner)
            for n, (_, _, color) in enumerate(settlements):
                m = (owner == n) & self.generated
                out[m] = out[m] + (np.array(color) - out[m]) * TERRITORY_TINT
        return np.clip(np.round(out * 255), 0, 255).astype(np.uint8)


def state_hash(entities: dict[int, dict], positions: dict[int, list], nations: list[dict]) -> str:
    state = {
        "entities": [
            [eid, e["kind"], e.get("nation", 0), positions.get(eid), e.get("visible", True)]
            for eid, e in sorted(entities.items())
        ],
        "nations": nations,
    }
    blob = json.dumps(state, sort_keys=True, separators=(",", ":")).encode()
    return hashlib.sha256(blob).hexdigest()[:16]


def convert(args: argparse.Namespace) -> Path:
    history, out = Path(args.history), Path(args.out)
    records = read_history(history)
    header = next(records, None)
    if not header or header.get("t") != "header" or header.get("format") != FORMAT:
        raise SystemExit(f"{history}: not a {FORMAT} file (run tools/BeyondNations.HistoryExport)")
    if args.stride % header["every"]:
        raise SystemExit(f"--stride {args.stride} must be a multiple of the export's --every {header['every']}")
    tile, chunks = scan_chunks(history)
    ground = Ground(chunks, tile, float(header["settlementJoinRange"]))
    tps = header["ticksPerSecond"]

    writer = ReplayWriter(
        out,
        sim="beyond-nations",
        sim_version=args.sim_version,
        seed=header["seed"],
        tick_rate=tps,
        state_hash_algorithm=(
            "export-frame SHA-256/64: canonical JSON of each entity's id, kind, nation, position and "
            "visibility plus the nation table, rebuilt from the HistoryExport stream"
        ),
        playback_rate=args.playback_rate,
        title=args.title or f"Beyond Nations, seed {header['seed']}",
        description=(
            f"{header['ticks']:,} ticks ({header['ticks'] // header['ticksPerDay']} in-game days) of a seeded world: "
            "pawns found nations and settlements, territory is drawn on the ground."
        ),
        source="tools/BeyondNations.HistoryExport + tools/history-to-replay.py",
        params={"ticks": header["ticks"], "every": header["every"], "stride": args.stride, "tileSize": tile},
    )
    with writer as w:
        for name, _kinds, label, color, shape in SETS:
            w.entity_set(name, label=label, color=color, width=SIZES[_kinds[0]], shape=shape)
        w.field(
            "ground",
            label="Ground and territory",
            cols=ground.cols,
            rows=ground.rows,
            origin=ground.origin,
            cell_size=tile,
        )

        positions: dict[int, list] = {}
        own_color: dict[int, tuple] = {}
        pending_chunks: list[dict] = []
        samples = 0
        for record in records:
            kind = record["t"]
            if kind == "chunk":
                pending_chunks.append(record)
                continue
            if kind != "frame":
                continue
            entities = {e["id"]: e for e in record["entities"]}
            for eid, e in entities.items():
                if "pos" in e:
                    positions[eid] = e["pos"]
                if "parts" in e:
                    own_color[eid] = tuple(e["parts"][0]["color"])
            tick = record["tick"]
            if tick % args.stride and tick != header["ticks"]:
                continue
            for chunk in pending_chunks:
                ground.add(chunk)
            pending_chunks.clear()
            nations = {n["id"]: n for n in record["nations"]}
            settlements = []
            groups: dict[str, dict[str, list]] = {s[0]: {"ids": [], "points": [], "colors": []} for s in SETS}
            counts = {"pawns": 0, "chickens": 0}
            for eid, e in sorted(entities.items()):
                k = e["kind"]
                if k == "pawn":
                    counts["pawns"] += 1
                elif k == "chicken":
                    counts["chickens"] += 1
                if k == "settlement" and e.get("nation") in nations:
                    x, _, z = positions[eid]
                    settlements.append((x, z, tuple(nations[e["nation"]]["color"])))
                target = next((s for s in SETS if k in s[1]), None)
                if target is None or e.get("visible", True) is False or eid not in positions:
                    continue
                x, y, z = positions[eid]
                g = groups[target[0]]
                g["ids"].append(eid)
                g["points"].append((x, -z, y + SIZES[k] / 2))
                if target[3] is None:
                    nation = nations.get(e.get("nation"))
                    g["colors"].append(to_bytes(nation["color"] if nation else NO_NATION))
            sample = {}
            for name, _kinds, _label, color, _shape in SETS:
                g = groups[name]
                sample[name] = {"ids": g["ids"], "points": g["points"]}
                if color is None:
                    sample[name]["colors"] = np.array(g["colors"], dtype=np.uint8).reshape(-1, 3)
            w.sample(
                tick,
                state_hash=state_hash(entities, positions, record["nations"]),
                entities=sample,
                fields={"ground": ground.colors(settlements)},
                stats={
                    "day": record.get("day", 0),
                    "pawns": counts["pawns"],
                    "settlements": len(settlements),
                    "nations": len(record["nations"]),
                    "chickens": counts["chickens"],
                },
            )
            samples += 1
    print(
        f"{out}: {samples} samples, ground {ground.cols}x{ground.rows} tiles, {out.stat().st_size:,} bytes",
        file=sys.stderr,
    )
    return out


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__.split("\n\n")[0])
    parser.add_argument("history", help="JSON Lines from tools/BeyondNations.HistoryExport")
    parser.add_argument("out", help="replay to write (.usdc, or .usda)")
    parser.add_argument("--stride", type=int, default=800, help="ticks per sample (a multiple of the export's --every)")
    parser.add_argument("--playback-rate", type=float, default=24000.0, help="suggested ticks per second of playback")
    parser.add_argument(
        "--sim-version", default="develop", help="Beyond Nations version or commit the history came from"
    )
    parser.add_argument("--title", default=None)
    convert(parser.parse_args(argv))
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
